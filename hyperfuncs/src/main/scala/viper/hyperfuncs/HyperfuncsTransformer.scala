package viper.hyperfuncs

import viper.silver.ast._
import viper.silver.plugin.sif.{SIFExtendedTransformer, SIFLowExp, SIFRelExp}
import viper.silver.verifier.errors.Internal
import viper.silver.verifier.reasons.{AssertionFalse, FeatureUnsupported}

import scala.collection.mutable

/**
  * The product construction of Viper's information-flow plugin (the "extended" encoding of Eilers, Müller & Hitz,
  * which supports branches on secrets), extended with hyperfunctions, `active(i)`, and partial `rel`. It overrides the
  * silver implementation ([[SIFExtendedTransformer]]) only where the semantics of hyperfunctions differs; the
  * semantics and the encoding are those of Gobra's PR #1127 (hyperfuncs paper, Section "Secret Control Flow"):
  *
  *  - `active(i)` holds if execution i is active at the current program point; it is the product's activation
  *    condition of execution i (including executions that returned or left a loop early);
  *  - `rel(e, i)` is partial: it is defined only if `active(i)` holds (`asserting active(i) in e_i`);
  *  - `low(e)` relates the active executions, as in Viper's plugin;
  *  - relational atoms are evaluated, like unary ones, in each active execution (Viper's plugin evaluated them only
  *    where both executions are active), so `!low(x)` is false where only one execution is active;
  *  - a hyperfunction H(x̄) becomes one function H(a₀, a₁, x̄, x̄') over the activation flags and the arguments of both
  *    executions. It reads the heap of execution 0 through the original fields and predicates and the heap of
  *    execution 1 through their copies, so hyperfunctions that read the heap may be recursive. Arguments for
  *    execution parameters are passed once. A hyperfunction that reads an execution must require that it is active
  *    in its precondition (e.g., `requires AllActive()`), which Viper's well-definedness check enforces;
  *  - termination proofs of hyperfunctions (generated by Viper's termination plugin) stay unary methods, in which
  *    relational values are replaced by unconstrained ones, so that every path through the body is checked.
  */
class HyperfuncsTransformer extends SIFExtendedTransformer {

  /** Names of hyperfunctions and, for each, the indices of its execution parameters (set by [[transformProgram]]). */
  var hyperFuncNames: Set[String] = Set.empty
  var execParams: Map[String, Set[Int]] = Map.empty
  /** The multiplicity rules (which expressions are rigid), see [[HyperfuncsChecks.isRigid]]. */
  private var multiplicity: HyperfuncsChecks = null
  private var hyperFunctions: Map[String, Function] = Map.empty

  def isHyperApp(e: Node): Boolean = e match {
    case f: FuncApp => hyperFuncNames(f.funcname)
    case _ => false
  }

  /** The constructs this class translates itself; the SIF plugin translates `low` and `lowEvent`. */
  private def isOwnRelational(e: Node): Boolean = e match {
    case _: SIFRelExp | _: HFActiveExp => true
    case f: FuncApp => hyperFuncNames(f.funcname)
    case _ => false
  }

  /**
    * Translates the program `p` (prepared by [[HyperfuncsPreprocessing]]) into a product program.
    */
  def transformProgram(p: Program, execParameters: Map[String, Set[Int]]): Program = {
    hyperFunctions = p.functions.filter(f => HyperfuncsAnnotations.isHyperfunction(f.info)).map(f => f.name -> f).toMap
    hyperFuncNames = hyperFunctions.keySet
    execParams = execParameters
    defaultValueFuncs.clear()
    anyValueFuncs.clear()
    multiplicity = new HyperfuncsChecks(p, hyperFuncNames, _ => ())
    transform(p, enableTiming = false)
  }

  /**
    * The SIF plugin's translation, with hyperfunctions replaced by abstract stubs, which are translated afterwards (the
    * SIF plugin rejects relational assertions in functions, and the translation of a hyperfunction needs the names of
    * the copies of fields and predicates for execution 1, which the SIF plugin creates).
    */
  override def transform(p: Program, enableTiming: Boolean): Program = {
    val stubs = p.functions.map(f =>
      if (hyperFuncNames(f.name)) f.copy(pres = Seq.empty, posts = Seq.empty, body = None)(f.pos, f.info, f.errT) else f)
    val withNames = p.copy(functions = stubs)(p.pos, p.info, p.errT)
    val product = super.transform(withNames, enableTiming)
    NameTransformer.markUsed(p.collect { case d: Declaration => d.name })
    val functions = product.functions.map(f => if (hyperFuncNames(f.name)) translateHyperFunction(hyperFunctions(f.name)) else f)
    val res = product.copy(functions = functions ++ defaultValueFuncs.values ++ anyValueFuncs.values)(product.pos, product.info, product.errT)
    Config.transformedProgramCallback.foreach(fn => fn(res))
    res
  }

  override def translateMethod(m: Method): Method =
    if (HyperfuncsAnnotations.isHyperfunction(m.info)) translateHyperfuncProofMethod(m) else super.translateMethod(m)

  override def isDirectlyUnary(e: Exp): Boolean = super.isDirectlyUnary(e) && !e.exists(isOwnRelational)

  // A relational atom is evaluated in each active execution, like a unary one: `rel(e, i)` is defined only if
  // execution i is active (see `translateRel`), and `low` relates the active executions.
  override def translateSIFExp1(e: Exp, p1: Exp, p2: Exp): Exp = translateNormal(e, p1, p2)
  override def translateSIFExp2(e: Exp, p1: Exp, p2: Exp): Exp = translatePrime(e, p1, p2)

  //////////////////////////////// Translation of `rel`, `active`, and hyperfunction calls ////////////////////////////////

  private var holeCounter = 0

  /**
    * Translates the constructs of this plugin in `e` first and the rest with the SIF plugin's `base` translation. The
    * already translated parts are hidden from `base` as leaves ([[HFHole]]), since `base` would otherwise translate
    * them again (e.g., rename the fields of execution 1 a second time).
    */
  private def withOwn[T <: Exp](e: T, p1: Exp, p2: Exp)(base: T => T): T = {
    val table = mutable.HashMap.empty[Int, Exp]
    val holed = e.transform {
      case x: Exp if isOwnRelational(x) =>
        val translated = translateOwn(x, p1, p2)
        holeCounter += 1
        table.update(holeCounter, translated)
        HFHole(holeCounter, x.typ)(x.pos)
    }
    val res = base(holed)
    if (table.isEmpty) res else res.transform { case h: HFHole if table.contains(h.id) => table(h.id) }
  }

  private def translateOwn(e: Exp, p1: Exp, p2: Exp): Exp = e match {
    case r: SIFRelExp => translateRel(r, p1, p2)
    case a: HFActiveExp => translateActive(a, p1, p2)
    case f: FuncApp => translateHyperFuncApp(f, p1, p2)
    case _ => e
  }

  override def translateNormal[T <: Exp](e: T, p1: Exp, p2: Exp): T = withOwn(e, p1, p2)(super.translateNormal(_, p1, p2))

  override def translatePrime[T <: Exp](e: T, p1: Exp, p2: Exp): T = withOwn(e, p1, p2)(super.translatePrime(_, p1, p2))

  override def translateToUnary(e: Exp): Exp = super.translateToUnary(e.transform {
    case a: Exp if a.typ == Bool && !isConnective(a) && a.exists(isOwnRelational) => TrueLit()(a.pos, a.info, a.errT)
  })

  override def translatePredLowFuncBody(e: Exp): Exp = e match {
    // a predicate's low function is used only where both executions are active
    case a if a.typ == Bool && !isConnective(a) && a.exists(isOwnRelational) =>
      val t = TrueLit()(a.pos)
      And(translateNormal(a, t, t), translatePrime(a, t, t))(a.pos, a.info, a.errT)
    case _ => super.translatePredLowFuncBody(e)
  }

  private def isConnective(e: Exp): Boolean = e match {
    case _: And | _: Or | _: Implies | _: Not => true
    case _ => false
  }

  /** The activation condition of execution `i` (an integer expression). */
  private def activeOf(i: Exp, p1: Exp, p2: Exp): Exp = i match {
    case IntLit(n) if n == 0 => p1
    case IntLit(_) => p2
    case _ => CondExp(EqCmp(i, IntLit(0)(i.pos))(i.pos), p1, p2)(i.pos, i.info, i.errT)
  }

  def translateActive(a: HFActiveExp, p1: Exp, p2: Exp): Exp = {
    requireActivation(a, p1, p2)
    activeOf(a.idx, p1, p2)
  }

  def translateRel(r: SIFRelExp, p1: Exp, p2: Exp): Exp = {
    requireActivation(r, p1, p2)
    if (!HyperfuncsConfig.enableRel)
      reportError(Internal(r, FeatureUnsupported(r, "rel-expressions are an experimental feature and must be explicitly enabled.")))
    val (act, e) = if (r.i.i == BigInt(1)) (p2, translatePrime(r.exp, p1, p2)) else (p1, translateNormal(r.exp, p1, p2))
    Asserting(activeCondition(act, r.i.i.toInt, r), e)(r.pos, r.info, r.errT)
  }

  /**
    * The activation condition `act` of execution `i`; errors read "Assertion active(i) might not hold", unless the
    * front end supplies the info of the condition ([[HyperfuncsConfig.activeConditionInfo]]).
    */
  private def activeCondition(act: Exp, i: Int, at: Node with Infoed with Positioned): Exp =
    HyperfuncsConfig.activeConditionInfo(at, i) match {
      case NoInfo =>
        val shown = HFActiveExp(IntLit(i)(at.pos))(at.pos)
        EqCmp(act, TrueLit()(at.pos))(at.pos, NoInfo, ReTrafo({ case AssertionFalse(_) => AssertionFalse(shown) }))
      case info => EqCmp(act, TrueLit()(at.pos))(at.pos, info, NoTrafos)
    }

  /** Placeholder values for the arguments of inactive executions: a literal, or an abstract function per type. */
  val defaultValueFuncs: mutable.LinkedHashMap[Type, Function] = mutable.LinkedHashMap.empty

  private def defaultValue(t: Type): Exp = t match {
    case Int => IntLit(0)()
    case Bool => FalseLit()()
    case Ref => NullLit()()
    case Perm => NoPerm()()
    case SeqType(e) => EmptySeq(e)()
    case SetType(e) => EmptySet(e)()
    case MultisetType(e) => EmptyMultiset(e)()
    case MapType(k, v) => EmptyMap(k, v)()
    case _ =>
      val f = defaultValueFuncs.getOrElseUpdate(t,
        Function(NameTransformer.getUnusedName("hf_placeholder"), Seq.empty, t, Seq.empty, Seq.empty, None)())
      FuncApp(f, Seq.empty)()
  }

  def translateHyperFuncApp(f: FuncApp, p1: Exp, p2: Exp): Exp = {
    requireActivation(f, p1, p2)
    val execs = execParams.getOrElse(f.funcname, Set.empty)
    val indexed = f.args.zipWithIndex
    val execArgs = indexed.collect { case (a, i) if execs(i) => translateNormal(a, p1, p2) }
    val args0 = indexed.collect { case (a, i) if !execs(i) => CondExp(p1, translateNormal(a, p1, p2), defaultValue(a.typ))(a.pos, a.info, a.errT) }
    val args1 = indexed.collect { case (a, i) if !execs(i) => CondExp(p2, translatePrime(a, p1, p2), defaultValue(a.typ))(a.pos, a.info, a.errT) }
    // errors show the call as written, not its translation over both executions
    val shown = ReTrafo({ case AssertionFalse(_) => AssertionFalse(f) })
    FuncApp(f.funcname, Seq(p1, p2) ++ execArgs ++ args0 ++ args1)(f.pos, f.info, f.typ, MakeTrafoPair(shown, f.errT))
  }

  private def requireActivation(n: Exp, p1: Exp, p2: Exp): Unit =
    if (p1 == null || p2 == null)
      reportError(Internal(n, FeatureUnsupported(n, "Relational expressions are not supported in this position.")))

  //////////////////////////////// Hyperfunction declarations ////////////////////////////////

  /** Unconstrained values, one abstract function per type, applied to a distinct literal at each use. */
  val anyValueFuncs: mutable.LinkedHashMap[Type, Function] = mutable.LinkedHashMap.empty
  private var anyValueCounter: Int = 0

  private def anyValue(t: Type, at: Positioned): Exp = {
    val f = anyValueFuncs.getOrElseUpdate(t,
      Function(NameTransformer.getUnusedName("hf_unconstrained"), Seq(LocalVarDecl("k", Int)()), t, Seq.empty, Seq.empty, None)())
    anyValueCounter += 1
    FuncApp(f, Seq(IntLit(anyValueCounter)(at.pos)))(at.pos)
  }

  /**
    * The termination proof that Viper's termination plugin generates for a hyperfunction. Termination is a property of
    * each execution, so the proof stays a unary method. Its relational values (`low`, `rel`, `active`, and calls of
    * hyperfunctions) are replaced by unconstrained values, a distinct one at each occurrence, such that every path
    * through the hyperfunction's body is checked; relational atoms in its precondition are dropped, which only
    * weakens the assumptions of the proof.
    */
  def translateHyperfuncProofMethod(m: Method): Method = {
    def isRelational(e: Node): Boolean = e match {
      case _: SIFLowExp => true
      case other => isOwnRelational(other)
    }
    def unconstrained(e: Exp): Exp = e.transform { case x: Exp if isRelational(x) => anyValue(x.typ, x) }
    val pres = m.pres.map(translateToUnary)
    val body = m.body.map(b => b.transform { case e: Exp => unconstrained(e) })
    m.copy(pres = pres, body = body)(m.pos, HyperfuncsAnnotations.withoutHyperfunctionAnnotations(m.info), m.errT)
  }

  /**
    * Translates a hyperfunction H(x̄) into H(a₀, a₁, ē, x̄, x̄'), where ē are the execution parameters: its contract and
    * body are translated with the activation flags a₀ and a₁, as assertions over the active executions (permissions of
    * an execution are required only if it is active). Every other parameter has one value per execution: a body
    * that needs a single value uses `rel(n, i)`.
    */
  def translateHyperFunction(f: Function): Function = {
    val primedBefore = primedNames.clone()
    val (a0d, a0) = getNewBool("act0")
    val (a1d, a1) = getNewBool("act1")
    val execs = execParams.getOrElse(f.name, Set.empty)
    val (execArgs, valueArgs) = f.formalArgs.zipWithIndex.partition { case (_, i) => execs(i) }
    val primedArgs = valueArgs.map { case (a, _) =>
      val newName = NameTransformer.getUnusedName(a.name)
      primedNames.update(a.name, newName)
      a.copy(name = newName)(a.pos, a.info, a.errT)
    }

    // rigid variables: the execution parameters (and `result`)
    val rigidVars = execArgs.map(_._1.name).toSet
    def assertion(e: Exp): Exp = hyperAssertion(e, a0, a1, rigidVars)
    // No implicit preconditions: a hyperfunction that reads an execution with `rel` must require that it is active
    // (e.g., `requires AllActive()`); otherwise, Viper's well-definedness check of the hyperfunction fails at the
    // read ("Assertion active(i) might not hold").
    val newPres = f.pres.map(assertion)
    val newPosts = f.posts.map(assertion)
    val newBody = f.body.map { b =>
      if (b.typ == Bool) assertion(b) else hyperValue(b, a0, a1, rigidVars)
    }
    primedNames.clear()
    primedNames ++= primedBefore
    f.copy(formalArgs = Seq(a0d, a1d) ++ execArgs.map(_._1) ++ valueArgs.map(_._1) ++ primedArgs,
      pres = newPres, posts = newPosts, body = newBody)(f.pos, HyperfuncsAnnotations.withoutHyperfunctionAnnotations(f.info), f.errT)
  }

  /**
    * An assertion over the active executions, for a hyperfunction's contract and boolean body. Unary atoms are lifted:
    * they must hold in each active execution. Rigid atoms (such as `active(1)`, `rel(x, 0) <= rel(x, 1)` or a call
    * of a hyperfunction) have one value for both executions and are evaluated once, also where no execution is
    * active; `rigid` are the names of the rigid variables in scope.
    */
  def hyperAssertion(e: Exp, a0: Exp, a1: Exp, rigid: Set[String]): Exp = {
    def rec(x: Exp): Exp = hyperAssertion(x, a0, a1, rigid)
    e match {
      case a@And(l, r) => And(rec(l), rec(r))(a.pos, a.info, a.errT)
      case o@Or(l, r) if isRelational(o) => Or(rec(l), rec(r))(o.pos, o.info, o.errT)
      case i@Implies(l, r) if isRelational(i) => Implies(rec(l), rec(r))(i.pos, i.info, i.errT)
      case n@Not(x) if isRelational(n) => Not(rec(x))(n.pos, n.info, n.errT)
      case c@CondExp(cond, t, f) if isRelational(c) => CondExp(rec(cond), rec(t), rec(f))(c.pos, c.info, c.errT)
      case l: SIFLowExp => Implies(And(a0, a1)(), translateSIFLowExpComparison(l, a0, a1))(l.pos, l.info, l.errT)
      case q@Forall(vars, triggers, body) if isRelational(q) =>
        val newTriggers = triggers.flatMap(t => Seq(
          Trigger(t.exps.map(x => translateNormal(x, a0, a1)))(t.pos, t.info, t.errT),
          Trigger(t.exps.map(x => translatePrime(x, a0, a1)))(t.pos, t.info, t.errT)))
        Forall(vars, newTriggers, hyperAssertion(body, a0, a1, rigid ++ vars.map(_.name)))(q.pos, q.info, q.errT)
      case q@Exists(vars, triggers, body) if isRelational(q) =>
        Exists(vars, triggers, hyperAssertion(body, a0, a1, rigid ++ vars.map(_.name)))(q.pos, q.info, q.errT)
      case u@Unfolding(pap: PredicateAccessPredicate, body) if isRelational(body) =>
        unfoldBoth(u, pap, rec(body), a0, a1)
      case e if isRelational(e) && multiplicity.isRigid(e, rigid) =>
        // a rigid atom: one value for both executions
        translateNormal(e, a0, a1)
      case e =>
        // a unary atom: evaluated in each active execution
        And(Implies(a0, translateNormal(e, a0, a1))(e.pos, e.info, e.errT),
          Implies(a1, translatePrime(e, a0, a1))(e.pos, e.info, e.errT))(e.pos, e.info, e.errT)
    }
  }

  /** A non-boolean hyperfunction body, which denotes one value for the tuple of executions. */
  def hyperValue(e: Exp, a0: Exp, a1: Exp, rigid: Set[String]): Exp = e match {
    case u@Unfolding(pap: PredicateAccessPredicate, body) if isRelational(body) =>
      unfoldBoth(u, pap, hyperValue(body, a0, a1, rigid), a0, a1)
    case c@CondExp(cond, t, f) if isRelational(c) =>
      val newCond = if (isRelational(cond)) hyperAssertion(cond, a0, a1, rigid) else translateNormal(cond, a0, a1)
      CondExp(newCond, hyperValue(t, a0, a1, rigid), hyperValue(f, a0, a1, rigid))(c.pos, c.info, c.errT)
    case e => translateNormal(e, a0, a1)
  }

  /** Unfolds the predicate instance in each active execution around `body`. */
  private def unfoldBoth(u: Unfolding, pap: PredicateAccessPredicate, body: Exp, a0: Exp, a1: Exp): Exp = {
    val pap0 = translateNormal(pap, a0, a1)
    val pap1 = translatePrime(pap, a0, a1)
    val second = CondExp(a1, Unfolding(pap1, body)(u.pos, u.info, u.errT), body)(u.pos, u.info, u.errT)
    CondExp(a0, Unfolding(pap0, second)(u.pos, u.info, u.errT), second)(u.pos, u.info, u.errT)
  }
}
